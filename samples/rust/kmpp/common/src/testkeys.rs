/// Map an optional CLI argument to a named RSA key size and its embedded key.
/// Accepts `2048`/`2k`, `3072`/`3k`, `4096`/`4k`; defaults to RSA-2048.
pub fn select_rsa(arg: Option<&str>) -> Result<(&'static str, &'static [u8]), String> {
    match arg.unwrap_or("2048").to_ascii_lowercase().as_str() {
        "2048" | "2k" => Ok(("RSA-2048", RSA_2048_KEY)),
        "3072" | "3k" => Ok(("RSA-3072", RSA_3072_KEY)),
        "4096" | "4k" => Ok(("RSA-4096", RSA_4096_KEY)),
        other => Err(format!(
            "unknown RSA key size '{other}'; expected one of: 2048, 3072, 4096"
        )),
    }
}

/// Map an optional CLI argument to a named EC curve and its embedded key.
/// Accepts `p256`/`p384`/`p521` (and `secp*`/`prime256v1` aliases); defaults to P-256.
pub fn select_ec(arg: Option<&str>) -> Result<(&'static str, &'static [u8]), String> {
    match arg.unwrap_or("p256").to_ascii_lowercase().as_str() {
        "p256" | "p-256" | "secp256r1" | "prime256v1" => Ok(("P-256", EC_P256_KEY)),
        "p384" | "p-384" | "secp384r1" => Ok(("P-384", EC_P384_KEY)),
        "p521" | "p-521" | "secp521r1" => Ok(("P-521", EC_P521_KEY)),
        other => Err(format!(
            "unknown curve '{other}'; expected one of: p256, p384, p521"
        )),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    // Guards against a truncated/empty embed: a DER private key is a SEQUENCE (0x30).
    #[test]
    fn embedded_keys_look_like_der() {
        for (name, key) in [
            ("RSA_2048_KEY", RSA_2048_KEY),
            ("RSA_3072_KEY", RSA_3072_KEY),
            ("RSA_4096_KEY", RSA_4096_KEY),
            ("EC_P256_KEY", EC_P256_KEY),
            ("EC_P384_KEY", EC_P384_KEY),
            ("EC_P521_KEY", EC_P521_KEY),
        ] {
            assert!(key.len() > 100, "{name}: too short ({} bytes)", key.len());
            assert_eq!(key[0], 0x30, "{name}: not a DER SEQUENCE");
        }
    }

    #[test]
    fn select_rsa_maps_sizes_and_default() {
        assert_eq!(select_rsa(None).unwrap().0, "RSA-2048");
        assert_eq!(select_rsa(Some("3k")).unwrap().0, "RSA-3072");
        assert_eq!(select_rsa(Some("4096")).unwrap().0, "RSA-4096");
        assert!(select_rsa(Some("1024")).is_err());
    }

    #[test]
    fn select_ec_maps_curves_and_default() {
        assert_eq!(select_ec(None).unwrap().0, "P-256");
        assert_eq!(select_ec(Some("p384")).unwrap().0, "P-384");
        assert_eq!(select_ec(Some("secp521r1")).unwrap().0, "P-521");
        assert!(select_ec(Some("p999")).is_err());
    }
}
